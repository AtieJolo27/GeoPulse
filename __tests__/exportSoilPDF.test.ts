import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { exportSoilHistoryPDF } from '../app/lib/exportSoilPDF';
import { historyLibMock } from './helpers/mocks';

const rows = [
  {
    created_at: '2026-11-10T08:00:00Z',
    nitrogen: 30,
    phosphorus: 15,
    potassium: 150,
    ph: 6.8,
    soil_moisture: 72,
    humidity: 65,
    soil_temperature: 24,
    air_temperature: 29,
  },
  { created_at: '2026-11-09T08:00:00Z', nitrogen: null, phosphorus: undefined },
];

describe('History tab - exportSoilHistoryPDF', () => {
  beforeEach(() => {
    historyLibMock.getSoilHistory.mockResolvedValue(rows);
    (Print.printToFileAsync as jest.Mock).mockResolvedValue({ uri: 'file:///report.pdf' });
    (Sharing.isAvailableAsync as jest.Mock).mockResolvedValue(true);
  });

  it('uses the same 30 readings as the chart', async () => {
    await exportSoilHistoryPDF();
    expect(historyLibMock.getSoilHistory).toHaveBeenCalledWith(30);
  });

  it('throws when there is no history', async () => {
    historyLibMock.getSoilHistory.mockResolvedValue([]);
    await expect(exportSoilHistoryPDF()).rejects.toThrow('No soil history available.');
    expect(Print.printToFileAsync).not.toHaveBeenCalled();
  });

  it('builds an HTML table with a row per reading and "-" for missing values', async () => {
    await exportSoilHistoryPDF();
    const { html } = (Print.printToFileAsync as jest.Mock).mock.calls[0][0];
    expect(html).toContain('30 mg/kg');
    expect(html).toContain('150 mg/kg');
    expect(html).toContain('6.8');
    expect(html).toContain('72%');
    expect(html).toContain('24 °C');
    expect(html).toContain('29 °C');
    expect(html).toContain('- mg/kg'); // null nitrogen / undefined phosphorus
    expect(html.match(/<td>/g)!.length).toBe(rows.length * 9);
    expect(html).toContain('Generated by Soil Quality Monitoring System');
  });

  it('opens the share sheet for the generated PDF and returns its uri', async () => {
    const uri = await exportSoilHistoryPDF();
    expect(uri).toBe('file:///report.pdf');
    expect(Sharing.shareAsync).toHaveBeenCalledWith(
      'file:///report.pdf',
      expect.objectContaining({ mimeType: 'application/pdf', UTI: 'com.adobe.pdf' })
    );
  });

  it('still returns the uri when sharing is unavailable', async () => {
    (Sharing.isAvailableAsync as jest.Mock).mockResolvedValue(false);
    const uri = await exportSoilHistoryPDF();
    expect(Sharing.shareAsync).not.toHaveBeenCalled();
    expect(uri).toBe('file:///report.pdf');
  });

  it('propagates PDF generation errors', async () => {
    (Print.printToFileAsync as jest.Mock).mockRejectedValue(new Error('print failed'));
    await expect(exportSoilHistoryPDF()).rejects.toThrow('print failed');
  });
});
