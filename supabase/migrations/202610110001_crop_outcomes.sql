-- Farmer-reported completed growing cycles, separate from prediction confidence.
CREATE TABLE IF NOT EXISTS public.crop_outcomes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_id bigint NOT NULL REFERENCES public.zones(id),
  crop text NOT NULL CHECK (length(trim(crop)) > 0),
  successful boolean NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS crop_outcomes_zone_idx ON public.crop_outcomes (zone_id, created_at);
-- Match access to the existing zone policies; never grant outcomes for inaccessible zones.
ALTER TABLE public.crop_outcomes ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT ON public.crop_outcomes TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.crop_outcomes_id_seq TO anon, authenticated;
CREATE POLICY crop_outcomes_read ON public.crop_outcomes FOR SELECT TO anon, authenticated
  USING (EXISTS (SELECT 1 FROM public.zones WHERE zones.id = crop_outcomes.zone_id));
CREATE POLICY crop_outcomes_insert ON public.crop_outcomes FOR INSERT TO anon, authenticated
  WITH CHECK (EXISTS (SELECT 1 FROM public.zones WHERE zones.id = crop_outcomes.zone_id));
